from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
import os

def generate_pdf_report(vehicle_info, diagnosis_result, output_path):
    """
    Generate a professional PDF diagnosis report.
    """
    doc = SimpleDocTemplate(output_path, pagesize=letter)
    styles = getSampleStyleSheet()
    elements = []

    # Title
    elements.append(Paragraph("AI Automobile Diagnosis Report", styles['Title']))
    elements.append(Spacer(1, 12))

    # Vehicle Info Section
    elements.append(Paragraph("Vehicle Information", styles['Heading2']))
    v_data = [
        ["Registration", vehicle_info.get('registration_number', 'N/A')],
        ["Manufacturer", vehicle_info.get('manufacturer', 'N/A')],
        ["Model", vehicle_info.get('model', 'N/A')],
        ["Year", str(vehicle_info.get('manufacturing_year', 'N/A'))],
        ["Mileage", f"{vehicle_info.get('current_mileage', 'N/A')} km"]
    ]
    v_table = Table(v_data, colWidths=[150, 300])
    v_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), colors.lightgrey),
        ('GRID', (0, 0), (-1, -1), 1, colors.black),
        ('PADDING', (0, 0), (-1, -1), 6)
    ]))
    elements.append(v_table)
    elements.append(Spacer(1, 20))

    # Diagnosis Results Section
    elements.append(Paragraph("Diagnosis Results", styles['Heading2']))
    d_data = [
        ["Predicted Fault", diagnosis_result['fault']],
        ["Confidence", f"{diagnosis_result['confidence']}%"],
        ["Severity", diagnosis_result['severity']],
        ["Symptoms", ", ".join(diagnosis_result['symptoms'])]
    ]
    d_table = Table(d_data, colWidths=[150, 300])
    d_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), colors.lightblue),
        ('GRID', (0, 0), (-1, -1), 1, colors.black),
        ('PADDING', (0, 0), (-1, -1), 6)
    ]))
    elements.append(d_table)
    elements.append(Spacer(1, 20))

    # Causes & Recommendations
    elements.append(Paragraph("Possible Causes", styles['Heading3']))
    for cause in diagnosis_result['causes']:
        elements.append(Paragraph(f"• {cause}", styles['Normal']))
    
    elements.append(Spacer(1, 12))
    elements.append(Paragraph("Recommended Action", styles['Heading3']))
    elements.append(Paragraph(diagnosis_result['recommendation'], styles['Normal']))
    
    elements.append(Spacer(1, 30))
    
    # Safety Disclaimer
    disclaimer_style = styles['Italic']
    disclaimer_style.fontSize = 8
    elements.append(Paragraph(
        "DISCLAIMER: This report is generated by an AI-assisted prototype for educational purposes. "
        "It is NOT a professional mechanical diagnosis. Please consult a qualified technician before "
        "performing any repairs or driving a vehicle with critical faults.", 
        disclaimer_style
    ))

    doc.build(elements)
    return output_path
